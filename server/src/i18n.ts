export type BotKey = keyof typeof uz;

const i18n = i18next.createInstance();
void i18n.init({
  resources: { uz: { translation: uz }, ru: { translation: ru } },
  lng: 'uz',
  fallbackLng: 'uz',
  interpolation: { escapeValue: false },
  initImmediate: false,
});

const fixed: Record<Language, TFunction> = {
  uz: i18n.getFixedT('uz'),
  ru: i18n.getFixedT('ru'),
};

export function t(lang: Language | null | undefined, key: BotKey, vars?: Record<string, unknown>): string {
  return String(fixed[lang === 'ru' ? 'ru' : 'uz'](key, vars as never));
}
